class Maintenance { // ประกาศสร้างคลาสชื่อ Maintenance
  int? id; // ตัวแปรเก็บรหัสไอดี (Primary Key) ใส่เครื่องหมาย ? หมายถึงสามารถเป็นค่าว่าง (null) ได้ตอนที่ยังไม่ได้บันทึกลงฐานข้อมูล
  String device; // ตัวแปรข้อความ เก็บชื่ออุปกรณ์ที่เสีย
  String issue; // ตัวแปรข้อความ เก็บอาการเสีย
  String urgency; // ตัวแปรข้อความ เก็บระดับความเร่งด่วน ("ปกติ", "ด่วน", "ด่วนที่สุด")
  DateTime createdAt; // ตัวแปรเก็บวัน/เดือน/ปี/เวลา ที่ทำการแจ้งซ่อม

  Maintenance({ // คอนสตรัคเตอร์ (Constructor) เป็นตัวรับค่าเข้ามาเมื่อมีการเรียกสร้างออบเจกต์ (Object) ใหม่
    this.id, // รับค่าไอดี (ไม่บังคับใส่)
    required this.device, // บังคับว่าต้องส่งค่าชื่ออุปกรณ์มานะ (required)
    required this.issue, // บังคับว่าต้องส่งค่าอาการเสียมานะ
    required this.urgency, // บังคับว่าต้องส่งค่าความเร่งด่วนมานะ
    required this.createdAt, // บังคับว่าต้องส่งค่าวันเวลามานะ
  }); // ปิดคอนสตรัคเตอร์

  // ฟังก์ชันนี้จะแปลงข้อมูลออบเจกต์ (Object) ให้กลายเป็นรูปแบบ Map (คีย์: ค่า) เพื่อให้ SQLite อ่านรู้เรื่อง
  Map<String, dynamic> toMap() { 
    return { // สั่งให้ส่งคืนค่า (return) ออกไปเป็นรูปแบบก้อน Map { ... }
      if (id != null) 'id': id, // ตรวจสอบว่าถ้า id ไม่ใช่ค่าว่าง ให้สร้างคีย์ 'id' และใส่ค่า id ลงไป
      'device': device, // สร้างคีย์ 'device' และเอาค่าตัวแปร device มาใส่
      'issue': issue, // สร้างคีย์ 'issue' และเอาค่าตัวแปร issue มาใส่
      'urgency': urgency, // สร้างคีย์ 'urgency' และเอาค่าตัวแปร urgency มาใส่
      'createdAt': createdAt.toString(), // แปลงวันเวลาที่เป็นแบบ DateTime ให้กลายเป็นข้อความ String ก่อน แล้วค่อยเก็บ
    }; // ปิดการส่งคืนค่า
  } // ปิดฟังก์ชัน toMap()
} // ปิดคลาส